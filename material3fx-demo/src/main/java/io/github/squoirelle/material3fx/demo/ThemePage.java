package io.github.squoirelle.material3fx.demo;

import io.github.squoirelle.material3fx.color.ColorRole;
import javafx.geometry.Insets;
import javafx.geometry.Pos;
import javafx.scene.Node;
import javafx.scene.control.Label;
import javafx.scene.layout.FlowPane;
import javafx.scene.layout.GridPane;
import javafx.scene.layout.Priority;
import javafx.scene.layout.StackPane;

import java.util.Locale;

/**
 * The generated color scheme, as swatches. Swatches are styled with the looked-up colors, so they
 * update live when the theme changes.
 */
final class ThemePage {

    private ThemePage() {
    }

    static Node page() {
        GridPane accents = new GridPane(8, 8);
        String[][] groups = {
                {"primary", "on-primary", "primary-container", "on-primary-container"},
                {"secondary", "on-secondary", "secondary-container", "on-secondary-container"},
                {"tertiary", "on-tertiary", "tertiary-container", "on-tertiary-container"},
                {"error", "on-error", "error-container", "on-error-container"},
        };
        for (int col = 0; col < groups.length; col++) {
            String[] g = groups[col];
            accents.add(swatch(g[0], g[1], 72), col, 0);
            accents.add(swatch(g[1], g[0], 40), col, 1);
            accents.add(swatch(g[2], g[3], 72), col, 2);
            accents.add(swatch(g[3], g[2], 40), col, 3);
            GridPane.setHgrow(accents.getChildren().getLast(), Priority.ALWAYS);
        }

        FlowPane surfaces = new FlowPane(8, 8);
        for (String role : new String[] {"surface-dim", "surface", "surface-bright", "surface-container-lowest",
                "surface-container-low", "surface-container", "surface-container-high", "surface-container-highest"}) {
            surfaces.getChildren().add(sized(swatch(role, "on-surface", 72), 160));
        }
        FlowPane others = new FlowPane(8, 8,
                sized(swatch("on-surface", "surface", 56), 160),
                sized(swatch("on-surface-variant", "surface", 56), 160),
                sized(swatch("outline", "surface", 56), 160),
                sized(swatch("outline-variant", "on-surface", 56), 160),
                sized(swatch("inverse-surface", "inverse-on-surface", 56), 160),
                sized(swatch("inverse-primary", "on-primary-container", 56), 160),
                sized(swatch("primary-fixed", "on-primary-fixed", 56), 160),
                sized(swatch("tertiary-fixed-dim", "on-tertiary-fixed", 56), 160));

        FlowPane custom = new FlowPane(8, 8,
                sized(customSwatch("success", "on-success", "Success"), 160),
                sized(customSwatch("success-container", "on-success-container", "Success container"), 160),
                sized(customSwatch("warning", "on-warning", "Warning"), 160),
                sized(customSwatch("warning-container", "on-warning-container", "Warning container"), 160));

        Label count = new Label(ColorRole.values().length + " roles are generated from one seed color, each with "
                + "translucent variants (-a08 ... -a38) for state layers and disabled states.");
        count.getStyleClass().add("on-surface-variant");
        count.setWrapText(true);

        return Gallery.page("Color scheme", "Everything below is generated by MaterialTheme from the seed color. "
                        + "Open the palette in the top bar to change it.",
                count,
                Gallery.section("Accent colors", accents),
                Gallery.section("Surfaces", surfaces),
                Gallery.section("Outlines, inverse and fixed roles", others),
                Gallery.section("Custom colors (harmonized with the primary)", custom));
    }

    private static Node swatch(String role, String textRole, double height) {
        Label name = new Label(role.replace('-', ' '));
        name.setStyle("-fx-text-fill: -md-sys-color-" + textRole + "; -fx-font-size: 12px;");
        StackPane box = new StackPane(name);
        StackPane.setAlignment(name, Pos.TOP_LEFT);
        box.setPadding(new Insets(8, 12, 8, 12));
        box.setMinHeight(height);
        box.setPrefHeight(height);
        box.setMinWidth(150);
        box.setMaxWidth(Double.MAX_VALUE);
        box.setStyle("-fx-background-color: -md-sys-color-" + role + "; -fx-background-radius: 8;"
                + (role.startsWith("surface") ? "-fx-border-color: -md-sys-color-outline-variant; -fx-border-radius: 8;" : ""));
        return box;
    }

    private static Node customSwatch(String role, String textRole, String title) {
        Label name = new Label(title);
        name.setStyle("-fx-text-fill: -md-custom-" + textRole + "; -fx-font-size: 12px;");
        StackPane box = new StackPane(name);
        StackPane.setAlignment(name, Pos.TOP_LEFT);
        box.setPadding(new Insets(8, 12, 8, 12));
        box.setMinHeight(72);
        box.setStyle("-fx-background-color: -md-custom-" + role.toLowerCase(Locale.ROOT) + "; -fx-background-radius: 8;");
        return box;
    }

    private static Node sized(Node node, double width) {
        ((StackPane) node).setPrefWidth(width);
        return node;
    }
}
